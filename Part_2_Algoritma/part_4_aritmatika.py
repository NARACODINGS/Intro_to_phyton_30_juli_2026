x = 3
y = 2

# Penjumlahan (+)
hasil = x + y
print(f"Hasil Penjumlahan : {x} + {y} = {hasil}")
# Pengurangan (-)
hasil = x - y
print(f"Hasil Pengurangan : {x} - {y} = {hasil}")
# Perkalian (*)
hasil = x * y
print(f"Hasi Perkalian : {x} * {y} = {hasil}")
# Pembagian Float (/)
hasil = x / y
print(f"Hasi Pembagian Float : {x} / {y} = {hasil}")
# Pembagian Interger (//)
hasil = x // y
print(f"Hasi Pembagian Interger : {x} // {y} = {hasil}")
# Sisa bagi (%)
hasil = x % y
print(f"Hasi Sisa bagi : {x} % {y} = {hasil}")
# Pangkat (**)
hasil = x ** y
print(f"Hasi Pangkat : {x} ** {y} = {hasil}")

# Increment (+=)
# hasil = hasil + 1 "Tidak baik Penulisannya"
hasil += 1
# Decerment (-=)
hasil -= 1
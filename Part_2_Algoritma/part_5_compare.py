x = 2
y = 2

# Besar dari (>)
hasil = x > y
print(f"Hasil dari {x} Besar dari (>) {y} = {hasil}")
# Besar dari sama dengan (>=)
hasil = x > y
print(f"Hasil dari {x} Besar dari sama dengan (>=) {y} = {hasil}")
# Kecil dari (<)
hasil = x < y
print(f"Hasil dari {x} Kecil dari (<) {y} = {hasil}")
# Kecil dari sama dengan (<=)
hasil = x <= y
print(f"Hasil dari {x} Kecil dari sama dengan (<=) {y} = {hasil}")
# Sama dengan (==)
x = 2
y = "2"
hasil = x == y
print(f"Hasil dari {x} Sama dengan (==) {y} = {hasil}") # True and False
# Tidak sama dengan (!=)
hasil = x != y
print(f"Hasil dari {x} Tidak sama dengan (!=) {y} = {hasil}")